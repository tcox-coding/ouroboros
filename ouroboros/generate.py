def _library_pose(name: str, size: tuple[int, int], run_dir: Path, cfg: dict, root: Path) -> Path | None:
    """A pose saved in the library (the same ones jobs use), drawn at the output size."""
    try:
        saved = pose_mod.PoseLibrary(root / "poses").get(name)
    except (FileNotFoundError, OSError, ValueError):
        return None
    if not pose_mod.has_body(saved):
        return None
    cn = cfg.get("controlnet", {})
    out = run_dir / "pose_control.png"
    # Keypoints are fractions of the pose's own image: drawn straight onto a frame of
    # another shape they'd be stretched, so they're cropped to it as the image would be.
    fitted = pose_mod.fit(saved, tuple(saved.get("size") or size), size)
    pose_mod.render(fitted, size, hands=cn.get("pose_hands", True),
                    face=cn.get("pose_face", False)).save(out)
    return out


def _pose_source(saved_pose: str, pose_ref: Path | None, root: Path) -> Path | None:
    """The image a pose comes from: the pose reference, or a library pose's source image."""
    if pose_ref is not None:
        return pose_ref
    if saved_pose:
        try:
            src = pose_mod.PoseLibrary(root / "poses").source(saved_pose)
            return src if src.is_file() else None
        except (FileNotFoundError, OSError):
            return None
    return None


def _pose_image(reference: Path, size: tuple[int, int], run_dir: Path, cfg: dict) -> Path | None:
    """The pose reference as an openpose skeleton at the output size."""
    found = pose_mod.detect(reference)
    if not pose_mod.has_body(found):
        return None
    with Image.open(reference) as img:
        src = img.size
    cn = cfg.get("controlnet", {})
    fitted = pose_mod.fit(found, src, size)
    out = run_dir / "pose_control.png"
    pose_mod.render(fitted, size, hands=cn.get("pose_hands", True),
                    face=cn.get("pose_face", False)).save(out)
    return out


def _work(p: GenParams, size: tuple[int, int], batch: int, ipa, control) -> dict:
    """What the render cost depends on: sampled steps x megapixels x images."""
    steps = p.steps * (p.denoise if p.mode != "txt2img" else 1.0)
    mp = size[0] * size[1] / 1e6
    return {"steps": round(steps, 1), "megapixels": round(mp, 3), "images": batch,
            "ipadapter": bool(ipa), "control": bool(control)}


def estimate(root: Path, recent: int = 12) -> dict:
    """Seconds per unit of render work (step x megapixel x image), from the last manual
    renders on this machine; the Home tab turns it into a time estimate. Falls back to a
    rough SDXL figure until there is history."""
    rates, llm = [], []
    for f in sorted((root / "runs" / "manual").glob("*/run.json"), reverse=True)[:60]:
        try:
            rec = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        t = rec.get("timing") or _timing_from_files(f.parent, rec)
        if not t:
            continue
        work = (t.get("steps") or 0) * (t.get("megapixels") or 0) * (t.get("images") or 0)
        if work and t.get("render_s"):
            extra = 1 + IPADAPTER_COST * bool(t.get("ipadapter")) + CONTROL_COST * bool(t.get("control"))
            rates.append(max(0.05, (t["render_s"] - FIXED_S) / (work * extra)))
        if t.get("llm_s"):
            llm.append(t["llm_s"])
        if len(rates) >= recent:
            break
    median = lambda xs: sorted(xs)[len(xs) // 2] if xs else None
    return {"rate": round(median(rates) or DEFAULT_RATE, 3), "fixed": FIXED_S, "llm": median(llm) or 20,
            "ipadapter": IPADAPTER_COST, "control": CONTROL_COST, "samples": len(rates)}


def _timing_from_files(run_dir: Path, rec: dict) -> dict | None:
    """Older runs have no timing: the folder is named when the render starts and the
    images are written when it ends. Only used when the LLM didn't write the prompt."""
    try:
        start = time.mktime(time.strptime(run_dir.name[:15], "%Y%m%d-%H%M%S"))
        images = list(run_dir.glob("image_*.png"))
        if not images or not rec.get("size") or not (rec.get("request") or {}).get("positive"):
            return None
        end = max(f.stat().st_mtime for f in images)
        fields = dict(x.split("=", 1) for x in rec["params"].split() if "=" in x)
        steps = int(fields["steps"]) * (float(fields["denoise"]) if not rec["params"].startswith("txt2img") else 1)
        w, h = rec["size"]
        return {"render_s": end - start, "steps": steps, "megapixels": w * h / 1e6, "images": len(images),
                "ipadapter": bool(rec.get("ipadapter")), "control": bool(rec.get("control"))}
    except (OSError, ValueError, KeyError, TypeError):
        return None


# Seconds of overhead per render (upload, VAE decode, fetching images), seconds per step
# per megapixel per image for SDXL before any history exists (RTX 2080 Ti on Linux), and
# the extra fraction the IP-Adapter and the pose ControlNet add.
FIXED_S = 4.0
DEFAULT_RATE = 0.6
IPADAPTER_COST = 0.3
CONTROL_COST = 0.4


